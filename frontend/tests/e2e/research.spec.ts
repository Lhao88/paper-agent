import { expect, test } from '@playwright/test'

test('create, approve, read, inspect evidence, edit and export a persisted review', async ({ page }, info) => {
  await page.goto('/projects')
  await page.getByLabel('项目名称').fill(`${info.project.metadata.projectPrefix} 学术检索研究`)
  await page.getByLabel('研究主题', { exact: true }).fill('合成资料中的检索与证据整理方法')
  await page.getByRole('button', { name: '建立项目 →' }).click()
  await page.getByRole('button', { name: '生成研究计划 →' }).click()
  await expect(page.getByLabel('研究问题 1')).toBeVisible({ timeout: 20000 })
  await page.getByLabel('研究问题 1').fill('检索方法如何围绕问题组织？')
  await page.getByRole('button', { name: '添加排除规则' }).click()
  await page.getByLabel('排除规则 1').fill('排除与主题无关的论文')
  await page.getByRole('button', { name: '确认规格并开始研究' }).click()
  await expect(page.getByText('已完成', { exact: true }).first()).toBeVisible({ timeout: 30000 })
  await expect(page.getByRole('heading', { name: '第 1 轮' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '第 2 轮' })).toBeVisible()
  await page.getByRole('link', { name: /阅读综述/ }).first().click()
  await expect(page.getByRole('heading', { name: '方法比较与进展分歧' })).toBeVisible()
  await page.getByRole('button', { name: '查看证据 1', exact: true }).first().click()
  await expect(page.getByRole('dialog', { name: '原文证据' })).toBeVisible()
  await expect(page.locator('.source-quote')).toContainText('ToyCorpus')
  await expect(page.getByRole('dialog', { name: '原文证据' }).getByText('支持', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '关闭 ×' }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: '方法比较与进展分歧' })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: '导出 Markdown ↓' }).click()
  expect((await download).suggestedFilename()).toMatch(/review-.+\.md/)
  await page.getByRole('button', { name: '编辑当前版本' }).click()
  await page.getByLabel('编辑段落', { exact: true }).first().fill('人工修订的讨论，仍需核验引用。')
  await page.getByRole('button', { name: '另存为新版本' }).click()
  await expect(page.getByText('人工修订的讨论，仍需核验引用。')).toBeVisible()
  await page.screenshot({ path: 'test-results/review-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy()
  await page.screenshot({ path: 'test-results/review-mobile.png', fullPage: true })
})
